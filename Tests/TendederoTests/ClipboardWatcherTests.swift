    @Test func replacementAfterValidationOrSaveDiscardsStaleWork() async throws {
        // Model a producer changing ownership while the worker runs, checking
        // both the validation boundary and the file-delivery boundary.
        for boundary in [2, 3] {
            try await withWatcher { watcher, source, folder, received in
                try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
                let existing = folder.appendingPathComponent("existing.png")
                try Data("preserve".utf8).write(to: existing)
                watcher.start()
                source.copy([[.png: try imageData()]])
                source.onDataRead = {
                    var checks = 0
                    source.onCountRead = {
                        checks += 1
                        if checks == boundary { source.count += 1; source.onCountRead = nil }
                    }
                    source.onDataRead = nil
                }
                await watcher.check()?.value
                #expect(received().isEmpty)
                #expect(try FileManager.default.contentsOfDirectory(atPath: folder.path) == ["existing.png"])
            }
        }
    }

