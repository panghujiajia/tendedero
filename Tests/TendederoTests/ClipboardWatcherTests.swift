    @Test func dataByteLimitAcceptsBoundaryAndRejectsOneByteOver() throws {
        var data = try imageData()
        // Add a complete private ancillary chunk before IEND to reach exactly 32 MiB.
        let payloadSize = ClipboardWatcher.maximumDataBytes - data.count - 12
        var chunk = Data()
        var length = UInt32(payloadSize).bigEndian
        withUnsafeBytes(of: &length) { chunk.append(contentsOf: $0) }
        chunk.append(Data("npAd".utf8))
        chunk.append(Data(count: payloadSize))
        var crc = chunk.dropFirst(4).withUnsafeBytes {
            UInt32(crc32(0, $0.bindMemory(to: UInt8.self).baseAddress, uInt($0.count))).bigEndian
        }
        withUnsafeBytes(of: &crc) { chunk.append(contentsOf: $0) }
        data.insert(contentsOf: chunk, at: data.count - 12)
        #expect(ClipboardWatcher.validatedPNG(data, type: .png) == data)
        data.append(0)
        #expect(ClipboardWatcher.validatedPNG(data, type: .png) == nil)
        #expect(ClipboardWatcher.validatedPNG(data, type: .tiff) == nil)
    }

    @Test func pixelLimitAcceptsFortyMillionAndRejectsOversizedHeaders() throws {
        let boundary = try imageData(width: 8000, height: 5000)
        #expect(ClipboardWatcher.validatedPNG(boundary, type: .png) == boundary)
        for (width, height) in [(8001, 5000), (Int(UInt32.max), Int(UInt32.max)), (0, 2)] {
            var png = try imageData()
            for (offset, dimension) in [(16, width), (20, height)] {
                for n in 0..<4 { png[offset + n] = UInt8(truncatingIfNeeded: UInt32(dimension) >> (24 - 8 * n)) }
            }
            var crc: UInt32 = 0xffffffff
            for byte in png[12..<29] {
                crc ^= UInt32(byte)
                for _ in 0..<8 { crc = (crc >> 1) ^ ((crc & 1) == 1 ? 0xedb88320 : 0) }
            }
            crc ^= 0xffffffff
            for n in 0..<4 { png[29 + n] = UInt8(truncatingIfNeeded: crc >> (24 - 8 * n)) }
            #expect(ClipboardWatcher.validatedPNG(png, type: .png) == nil)
        }
    }
