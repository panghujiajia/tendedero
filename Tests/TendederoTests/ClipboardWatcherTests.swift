/// Synthetic metadata, bytes and URLs only; never opens NSPasteboard.general.
@MainActor
private final class FakeClipboard: ClipboardSource {
    var count = 0
    var items: [[NSPasteboard.PasteboardType: Data]] = []
    var boardTypes: [NSPasteboard.PasteboardType] = []
    var urls: [URL] = []
    var countReads = 0
    var typeReads = 0
    var dataReads: [NSPasteboard.PasteboardType] = []
    var urlReads = 0
    var onTypesRead: (() -> Void)?
    var onDataRead: (() -> Void)?
    var onURLsRead: (() -> Void)?
    var onCountRead: (() -> Void)?

    var changeCount: Int { countReads += 1; onCountRead?(); return count }
    var types: [NSPasteboard.PasteboardType] { boardTypes }
    var itemTypes: [[NSPasteboard.PasteboardType]] {
        typeReads += 1
        let result = items.map { Array($0.keys) }
        onTypesRead?()
        return result
    }
    func data(forType type: NSPasteboard.PasteboardType, at index: Int) -> Data? {
        dataReads.append(type)
        let result = items[index][type]
        onDataRead?()
        return result
    }
    func fileURLs() -> [URL] {
        urlReads += 1
        let result = urls
        onURLsRead?()
        return result
    }
    func copy(_ items: [[NSPasteboard.PasteboardType: Data]]) {
        count += 1
        self.items = items
    }
}

extension IntegrationSuite {
@MainActor
final class ClipboardWatcherTests: TestFiles {
    private func imageData(_ type: UTType = .png, width: Int = 2, height: Int = 2) throws -> Data {
        let context = try #require(CGContext(data: nil, width: width, height: height,
            bitsPerComponent: 8, bytesPerRow: 0, space: CGColorSpaceCreateDeviceGray(),
            bitmapInfo: CGImageAlphaInfo.none.rawValue))
        context.setFillColor(gray: 0.4, alpha: 1)
        context.fill(CGRect(x: 0, y: 0, width: width, height: height))
        let data = NSMutableData()
        let destination = try #require(CGImageDestinationCreateWithData(data, type.identifier as CFString, 1, nil))
        CGImageDestinationAddImage(destination, try #require(context.makeImage()), nil)
        try #require(CGImageDestinationFinalize(destination))
        return data as Data
    }

    private func withWatcher(_ body: (ClipboardWatcher, FakeClipboard, URL, () -> [URL]) async throws -> Void) async throws {
        let source = FakeClipboard()
        let folder = root.appendingPathComponent(UUID().uuidString, isDirectory: true)
        var received: [URL] = []
        let watcher = ClipboardWatcher(source: source, folder: folder) { received.append($0) }
        defer { watcher.stop() }
        try await body(watcher, source, folder, { received })
    }

    @Test func disabledStartAndRestartNeverImportExistingContents() async throws {
        try await withWatcher { watcher, source, folder, received in
            source.copy([[.png: try imageData()]])
            await watcher.check()?.value
            #expect(source.countReads == 0 && source.typeReads == 0 && source.dataReads.isEmpty)
            watcher.start()
            await watcher.check()?.value
            #expect(source.typeReads == 0)
            watcher.stop()
            let reads = source.countReads
            source.copy([[.png: try imageData()]])
            await watcher.check()?.value
            #expect(source.countReads == reads)
            watcher.start()
            await watcher.check()?.value
            #expect(received().isEmpty)
            #expect(!FileManager.default.fileExists(atPath: folder.path))
            source.copy([[.png: try imageData()]])
            watcher.start() // Must not reset the baseline on a second start.
            await watcher.check()?.value
            #expect(received().count == 1)
        }
    }

    @Test func allPrivacyAndOwnMarkersPreflightEveryItemIncludingFinder() async throws {
        let markers = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                       "org.nspasteboard.AutoGeneratedType", ClipboardWatcher.ownType.rawValue]
        for marker in markers {
            for placement in 0..<3 {
                for finder in [false, true] {
                    try await withWatcher { watcher, source, folder, received in
                        watcher.start()
                        var entry: [NSPasteboard.PasteboardType: Data] = [.png: try imageData()]
                        if finder { entry[.fileURL] = Data("file:///synthetic.png".utf8) }
                        source.copy([entry])
                        let type = NSPasteboard.PasteboardType(marker)
                        if placement == 0 { source.items[0][type] = Data() }
                        if placement == 1 { source.items.append([type: Data()]) }
                        if placement == 2 { source.boardTypes = [type] }
                        source.urls = [URL(fileURLWithPath: "/synthetic.png")]
                        await watcher.check()?.value
                        #expect(source.dataReads.isEmpty && source.urlReads == 0)
                        #expect(received().isEmpty)
                        #expect(!FileManager.default.fileExists(atPath: folder.path))
                    }
                }
            }
        }
    }

    @Test func pngBytesPreservedAndMultipleItemsProduceOneCapture() async throws {
        try await withWatcher { watcher, source, folder, received in
            watcher.start()
            let png = try imageData()
            source.copy([[.png: png, .tiff: try imageData(.tiff), .string: Data("unread".utf8)], [.png: png]])
            let before = source.items, count = source.count
            await watcher.check()?.value
            await watcher.check()?.value
            let url = try #require(received().first)
            #expect(received().count == 1)
            #expect(try Data(contentsOf: url) == png)
            #expect(url.deletingLastPathComponent() == folder)
            #expect(source.items == before && source.count == count)
            #expect(source.dataReads == [.png])
        }
    }

    @Test func tiffFallbackRetainsPixelsAndDimensions() async throws {
        try await withWatcher { watcher, source, _, received in
            watcher.start()
            let tiff = try imageData(.tiff, width: 7, height: 3)
            source.copy([[.png: Data("invalid".utf8), .tiff: tiff]])
            await watcher.check()?.value
            let url = try #require(received().first)
            let saved = try #require(CGImageSourceCreateWithURL(url as CFURL, nil))
            let original = try #require(CGImageSourceCreateWithData(tiff as CFData, nil))
            let a = try #require(CGImageSourceCreateImageAtIndex(original, 0, nil))
            let b = try #require(CGImageSourceCreateImageAtIndex(saved, 0, nil))
            #expect(CGImageSourceGetType(saved) as String? == UTType.png.identifier)
            #expect(b.width == 7 && b.height == 3)
            #expect(a.dataProvider?.data as Data? == b.dataProvider?.data as Data?)
            #expect(source.items[0][.tiff] == tiff)
            #expect(source.dataReads == [.png, .tiff])
        }
    }

    @Test func laterImageItemAndUnsupportedContent() async throws {
        try await withWatcher { watcher, source, _, received in
            watcher.start()
            let text: [NSPasteboard.PasteboardType: Data] = [.string: Data("unread".utf8),
                .URL: Data("https://example.invalid/image.png".utf8), .init("public.jpeg"): try imageData(.jpeg)]
            source.copy([text])
            await watcher.check()?.value
            source.copy([])
            await watcher.check()?.value
            #expect(source.dataReads.isEmpty && source.urlReads == 0 && received().isEmpty)
            source.copy([text, [.png: try imageData()]])
            await watcher.check()?.value
            #expect(received().count == 1 && source.dataReads == [.png])
        }
    }

    @Test func finderUsesOriginalFilesAndNeverReadsTheirIcons() async throws {
        try await withWatcher { watcher, source, folder, received in
            watcher.start()
            let original = root.appendingPathComponent("original.PNG")
            let bytes = try imageData()
            try bytes.write(to: original)
            source.copy([[.png: bytes], [.fileURL: Data(original.absoluteString.utf8)]])
            source.urls = [original, root.appendingPathComponent("notes.txt"), URL(string: "https://example.invalid/a.png")!]
            await watcher.check()?.value
            await watcher.check()?.value
            #expect(received() == [original])
            #expect(source.dataReads.isEmpty && source.urlReads == 1)
            #expect(!FileManager.default.fileExists(atPath: folder.path))
            #expect(try Data(contentsOf: original) == bytes)
        }
    }

    @Test func changesDuringMetadataImageAndFinderReadsAreDiscarded() async throws {
        for stage in ["metadata", "data", "finder"] {
            try await withWatcher { watcher, source, folder, received in
                watcher.start()
                source.copy([[.png: try imageData()]])
                if stage == "metadata" {
                    source.onTypesRead = { source.count += 1; source.onTypesRead = nil }
                } else if stage == "data" {
                    source.onDataRead = { source.count += 1; source.onDataRead = nil }
                } else {
                    source.items[0][.fileURL] = Data()
                    source.urls = [root.appendingPathComponent("original.png")]
                    source.onURLsRead = { source.count += 1; source.onURLsRead = nil }
                }
                await watcher.check()?.value
                #expect(received().isEmpty)
                #expect(!FileManager.default.fileExists(atPath: folder.path))
                if stage == "metadata" { #expect(source.dataReads.isEmpty && source.urlReads == 0) }
                await watcher.check()?.value
                #expect(received().count == 1, "The next stable copy must still be accepted")
            }
        }
    }

    @Test func replacementBeforeQueuedReadIsNotReadOrCaptured() async throws {
