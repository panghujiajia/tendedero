    @Test func validationRejectsCorruptEmptyAndMislabeledImages() throws {
        let png = try imageData(), tiff = try imageData(.tiff)
        for data in [Data(), Data("invalid".utf8), Data(png.prefix(33)), Data(png.dropLast(20)), try imageData(.jpeg)] {
            #expect(ClipboardWatcher.validatedPNG(data, type: .png) == nil)
        }
        #expect(ClipboardWatcher.validatedPNG(Data(tiff.prefix(16)), type: .tiff) == nil)
