/// Metadata and reads are injectable so race/privacy tests use no system clipboard.
@MainActor
protocol ClipboardSource {
    var changeCount: Int { get }
    var types: [NSPasteboard.PasteboardType] { get }
    var itemTypes: [[NSPasteboard.PasteboardType]] { get }
    func data(forType type: NSPasteboard.PasteboardType, at index: Int) -> Data?
    func fileURLs() -> [URL]
}

@MainActor
private struct SystemClipboardSource: ClipboardSource {
    let providedBoard: NSPasteboard?
    // Constructing a disabled watcher must not access the general pasteboard.
    private var board: NSPasteboard { providedBoard ?? .general }
    var changeCount: Int { board.changeCount }
    var types: [NSPasteboard.PasteboardType] { board.types ?? [] }
    var itemTypes: [[NSPasteboard.PasteboardType]] { board.pasteboardItems?.map(\.types) ?? [] }
    func data(forType type: NSPasteboard.PasteboardType, at index: Int) -> Data? {
        guard let items = board.pasteboardItems, items.indices.contains(index) else { return nil }
        return items[index].data(forType: type)
    }
    func fileURLs() -> [URL] {
        board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL] ?? []
    }
}

/// Hangs images copied to the clipboard: a screenshot taken with Control
/// held, "Copy Image" in a browser, or an image file copied in Finder.
/// The pasteboard has no change notification, so it is polled.
@MainActor
final class ClipboardWatcher {
    private let onImage: (URL) -> Void
    private var timer: Timer?
    private var lastCount: Int?
    private let source: any ClipboardSource
    private let destination: URL
    private var generation = UUID()
    private var active = false
    static let ownType = NSPasteboard.PasteboardType("app.tendedero.copied-image")
    nonisolated static let folder = Inbox.defaultFolder.deletingLastPathComponent()
        .appendingPathComponent("Clipboard", isDirectory: true)

    private static let enabledKey = "clipboardEnabled"
    private static let offeredKey = "clipboardOffered"

    /// Off until the user turns it on: reading the clipboard is their call.
    static var isEnabled: Bool {
        get { UserDefaults.standard.bool(forKey: enabledKey) }
        set { UserDefaults.standard.set(newValue, forKey: enabledKey) }
    }

    /// Whether we already asked, so the offer appears only once.
    static var wasOffered: Bool {
        get { UserDefaults.standard.bool(forKey: offeredKey) }
        set { UserDefaults.standard.set(newValue, forKey: offeredKey) }
    }

    private static let imageExtensions: Set<String> = ["png", "jpg", "jpeg", "heic", "tif", "tiff", "gif", "webp", "bmp"]
    /// Marked by password managers and similar apps as not for history tools.
    private static let privateTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                       "org.nspasteboard.AutoGeneratedType"].map { NSPasteboard.PasteboardType($0) }

    nonisolated static let maximumDataBytes = 32 * 1024 * 1024
    nonisolated static let maximumPixelCount = 40_000_000

    convenience init(board: NSPasteboard? = nil, folder: URL = ClipboardWatcher.folder,
                     onImage: @escaping (URL) -> Void) {
        self.init(source: SystemClipboardSource(providedBoard: board), folder: folder, onImage: onImage)
    }

    init(source: any ClipboardSource, folder: URL, onImage: @escaping (URL) -> Void) {
        self.onImage = onImage
        self.source = source
        destination = folder
    }

    func start() {
        guard timer == nil else { return }
        // Whatever is on the clipboard already is old news.
        lastCount = source.changeCount
        active = true
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { _ = self?.check() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        active = false
        generation = UUID()
        timer?.invalidate()
        timer = nil
    }

    @discardableResult
    func check() -> Task<Void, Never>? {
        guard active else { return nil }
        let count = source.changeCount
        guard count != lastCount else { return nil }
        lastCount = count
        let token = generation
        let types = source.types
        let items = source.itemTypes
        let allTypes = types + items.flatMap { $0 }
        // Preflight every item before requesting image bytes or Finder URLs.
        guard !allTypes.contains(where: { Self.privateTypes.contains($0) || $0 == Self.ownType }),
              isCurrent(count, token) else { return nil }

        // Files copied in Finder: hang the image files themselves. Finder also
        // puts the file's icon on the clipboard, which must not be hung.
        if allTypes.contains(.fileURL) {
            let urls = source.fileURLs()
            guard isCurrent(count, token) else { return nil }
            for url in urls where url.isFileURL && Self.imageExtensions.contains(url.pathExtension.lowercased()) {
                guard isCurrent(count, token) else { return nil }
                onImage(url)
            }
            return nil
        }

        let candidates = items.enumerated().flatMap { index, types in
            [NSPasteboard.PasteboardType.png, .tiff].filter { types.contains($0) }.map { (index, $0) }
        }
        guard !candidates.isEmpty else { return nil }
        return Task { [weak self] in
            guard let self else { return }
            for (index, type) in candidates {
                guard self.isCurrent(count, token) else { return }
                let data = self.source.data(forType: type, at: index)
                guard self.isCurrent(count, token) else { return }
                guard let data, !data.isEmpty, data.count <= Self.maximumDataBytes else { continue }
                let png = await Task.detached(priority: .userInitiated) {
                    autoreleasepool { Self.validatedPNG(data, type: type) }
                }.value
                guard self.isCurrent(count, token) else { return }
                guard let png else { continue }
                let destination = self.destination
                let url = await Task.detached(priority: .userInitiated) {
                    Self.save(png, in: destination)
                }.value
                guard let url else { return }
                guard self.isCurrent(count, token) else {
                    try? FileManager.default.removeItem(at: url)
                    return
                }
                self.onImage(url)
                return // Multiple representations/items still make one generated capture.
            }
        }
    }

    private func isCurrent(_ count: Int, _ token: UUID) -> Bool {
        active && generation == token && source.changeCount == count
    }

    /// Adapted from PR #42: bound input and dimensions before decoding.
    nonisolated static func validatedPNG(_ data: Data, type: NSPasteboard.PasteboardType) -> Data? {
        guard !data.isEmpty, data.count <= maximumDataBytes, type == .png || type == .tiff,
              let source = CGImageSourceCreateWithData(data as CFData,
                [kCGImageSourceShouldCache: false] as CFDictionary),
              CGImageSourceGetType(source) as String? == (type == .png ? UTType.png.identifier : UTType.tiff.identifier),
              CGImageSourceGetStatus(source) == .statusComplete,
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = (properties[kCGImagePropertyPixelWidth] as? NSNumber)?.intValue,
              let height = (properties[kCGImagePropertyPixelHeight] as? NSNumber)?.intValue,
              width > 0, height > 0, width <= maximumPixelCount / height else { return nil }

        if type == .png {
            guard completePNGChunks(data) else { return nil }
            let options: [CFString: Any] = [
                kCGImageSourceCreateThumbnailFromImageAlways: true,
                kCGImageSourceThumbnailMaxPixelSize: 1,
                kCGImageSourceShouldCacheImmediately: true
            ]
            guard CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) != nil,
                  CGImageSourceGetStatusAtIndex(source, 0) == .statusComplete else { return nil }
            return data
        }
        guard let image = CGImageSourceCreateImageAtIndex(source, 0,
                [kCGImageSourceShouldCacheImmediately: true] as CFDictionary),
              CGImageSourceGetStatusAtIndex(source, 0) == .statusComplete,
              let png = pngData(image), png.count <= maximumDataBytes else { return nil }
        return png
    }

    /// ImageIO tolerates truncated PNGs and bad CRCs; require intact chunks and IEND.
    nonisolated private static func completePNGChunks(_ data: Data) -> Bool {
        data.withUnsafeBytes { buffer in
            guard let bytes = buffer.bindMemory(to: UInt8.self).baseAddress else { return false }
            func uint32(_ offset: Int) -> UInt32 {
                buffer.loadUnaligned(fromByteOffset: offset, as: UInt32.self).bigEndian
            }
            var offset = 8 // ImageIO has already verified the PNG signature/type.
            while offset <= data.count - 12 {
                let length = Int(uint32(offset))
                guard length <= data.count - offset - 12,
                      UInt32(crc32(0, bytes.advanced(by: offset + 4), uInt(length + 4))) == uint32(offset + 8 + length)
                else { return false }
                if uint32(offset + 4) == 0x49454e44 { // IEND
                    return length == 0 && offset + 12 == data.count
                }
                offset += length + 12
            }
            return false
        }
    }

    nonisolated private static func save(_ data: Data, in folder: URL) -> URL? {
        let url = folder.appendingPathComponent("Clipboard \(UUID().uuidString).png")
        do {
            try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true,
                                                    attributes: [.posixPermissions: 0o700])
            // Exclusive creation and mode 0600 protect bytes from the first write.
            let fd = open(url.path, O_WRONLY | O_CREAT | O_EXCL | O_NOFOLLOW, 0o600)
            guard fd >= 0 else { throw POSIXError(.init(rawValue: errno) ?? .EIO) }
            let handle = FileHandle(fileDescriptor: fd, closeOnDealloc: true)
            do {
                try handle.write(contentsOf: data)
                try handle.close()
            } catch {
                try? handle.close()
                try? FileManager.default.removeItem(at: url)
                throw error
            }
            return url
        } catch {
            log.error("Could not save a clipboard image")
            return nil
        }
    }
}
